import assert from 'node:assert/strict';
import {allLessons,levelLessons,progressionFor,canAccessLesson,SPECIALIST_TRACKS} from '../functions/lib/academy.js';
const completed=(ids,score=90)=>ids.map(lesson_id=>({lesson_id,status:'completed',score}));
assert.ok(allLessons().length>0,'academy must have lessons');
assert.equal(SPECIALIST_TRACKS.length,9,'all agreed specialist tracks must exist');
let p=[];
let g=progressionFor(p);
assert.equal(g.levels.beginner.unlocked,true);
assert.equal(g.levels.intermediate.unlocked,false);
assert.equal(g.levels.advanced.unlocked,false);
assert.equal(canAccessLesson(levelLessons('beginner')[0].id,p).allowed,true,'first beginner lesson must be open');
assert.equal(canAccessLesson(levelLessons('beginner')[1].id,p).allowed,false,'later beginner lesson must require previous completion');
assert.equal(canAccessLesson(levelLessons('intermediate')[0].id,p).allowed,false,'intermediate direct access must be blocked');
p=completed(levelLessons('beginner').map(x=>x.id),90);
g=progressionFor(p);
assert.equal(g.levels.beginner.passed,true);
assert.equal(g.levels.intermediate.unlocked,true);
assert.equal(g.levels.advanced.unlocked,false);
assert.equal(canAccessLesson(levelLessons('intermediate')[0].id,p).allowed,true);
const low=completed(levelLessons('beginner').map(x=>x.id),70);
assert.equal(progressionFor(low).levels.intermediate.unlocked,false,'completion without mastery must not unlock intermediate');
p=[...p,...completed(levelLessons('intermediate').map(x=>x.id),90)];
g=progressionFor(p);
assert.equal(g.levels.intermediate.passed,true);
assert.equal(g.levels.advanced.unlocked,true);
assert.equal(canAccessLesson(levelLessons('advanced')[0].id,p).allowed,true);
console.log('academy phase 1 progression gate: PASS');
